"""
Пользовательские фильтры для шаблонов.

Используется в шаблонах как:
    {{ value|intspace }}

Фильтр `intspace` форматирует числа в русском стиле:
- Разделители тысяч — пробелы
- Десятичный разделитель — запятая
- Два знака после запятой

Примеры:
    1234567.89  → "1 234 567,89"
    1000        → "1 000,00"
    "1234,56"   → "1 234,56"
"""

from django import template

# Регистрация библиотеки шаблонных фильтров
register = template.Library()


@register.filter
def intspace(value):
    """
    Форматирует число в русском стиле: пробелы между разрядами,
    запятая как десятичный разделитель, два знака после запятой.

    Если значение не является числом, возвращает его как есть.
    """
    if value is None:
        return "0"
    try:
        # Парсим значение: запятые и пробелы из исходной строки
        # не должны мешать парсингу
        num = float(str(value).replace(",", ".").replace(" ", ""))
    except ValueError:
        # Не удалось распарсить как число — возвращаем как есть
        return value
    # Форматируем: {:,} ставит запятые между разрядами, .2f — два знака.
    # Затем заменяем запятые на пробелы, а точку на запятую.
    return f"{num:,.2f}".replace(",", " ").replace(".", ",")
