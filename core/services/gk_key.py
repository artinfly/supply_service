"""Единый формат ключа ГК в справочнике и в отчёте.

Форматы ключей:
    игк                 6066
    игк/111сб           6066/162сб
    + спец (номер)      6066 5        6066/162сб 5

игк — последние 4 цифры номера ИГК, 111сб — номер сборочного контракта,
число после пробела — номер «спец…/N» из договора. «1234», «1234/34сб»
и «1234 5» — разные ГК.
"""

import re

# --- Регулярные выражения для парсинга ключей ГК ---


# ГК с номером сборочного контракта: «6066/162сб» или «6066_162сб»
_GK_RE = re.compile(r"(\d{4})(?!\d)\s*[/_\s\-]*\s*(\d+)\s*[сc]б", re.IGNORECASE)

# Только базовый ГК (4 цифры) с опциональным спец-номером: «6066» или «6066 5»
_BASE_ONLY_RE = re.compile(
    r"^\s*(\d{4})(?:[\s_/\-]+(?:спец\D*?)?(\d+))?\s*$", re.IGNORECASE
)

# Хвост со спец-номером после основного ключа: « 5» или «/5»
_SPEC_TAIL_RE = re.compile(r"^[\s_/\-]*(?:спец\D*?)?(\d+)\s*$", re.IGNORECASE)

# Спец-номер внутри строки договора: «спец…/5»
_SPEC_CONTRACT_RE = re.compile(r"спец.*/\s*(\d+)", re.IGNORECASE)

# Последние 4 цифры числа (для извлечения ИГК из длинного номера)
_LAST4_RE = re.compile(r"(\d{4})(?!\d)")


# --- Вспомогательные функции ---


def _compose(head, spec):
    """Собирает ключ ГК из базовой части и спец-номера.

    Args:
        head: базовая часть (например, «6066» или «6066/162сб»)
        spec: спец-номер или None

    Returns:
        str: «6066 5» или «6066» (без лишнего пробела, если spec=None)
    """
    return f"{head} {spec}" if spec else head


# --- Парсинг ключей ГК ---


def parse_gk_key(value):
    """Извлекает ключ ГК из метки/ключа файла.

    Примеры:
        «6066 162сб_5» -> «6066/162сб 5»
        «6066» -> «6066»
        «abc» -> None

    Args:
        value: строка или число для парсинга

    Returns:
        str или None: нормализованный ключ, если удалось распознать
    """
    text = str(value or "").strip()

    # Попытка 1: ГК с номером сборочного контракта
    m = _GK_RE.search(text)
    if m:
        head = f"{m.group(1)}/{m.group(2)}сб"
        tail = _SPEC_TAIL_RE.match(text[m.end() :])
        return _compose(head, tail.group(1) if tail else None)

    # Попытка 2: только базовый ГК (4 цифры) с опциональным спец-номером
    m = _BASE_ONLY_RE.match(text)
    if m:
        return _compose(m.group(1), m.group(2))

    return None


def gk_key(value):
    """Возвращает нормализованный ключ ГК. Если разобрать не удалось — исходная строка.

    Args:
        value: строка или число

    Returns:
        str: нормализованный ключ или исходное значение
    """
    text = str(value or "").strip()
    return parse_gk_key(text) or text


def key_from_contract(text):
    """Извлекает ключ ГК из строки «Договор/Дата».

    Примеры:
        «…06066/162сб/137 от 16.03.2021г.»            -> «6066/162сб»
        «…06066/137 от 16.03.2021г.»                  -> «6066»
        «…0984/81сб/137 от 10.02.2021г. спец…/5»      -> «0984/81сб 5»

    Args:
        text: строка с номером договора и датой

    Returns:
        str или None: извлечённый ключ ГК
    """
    text = str(text or "")

    # Извлекаем базовую часть: ГК с номером сборочного контракта или только 4 цифры
    m = _GK_RE.search(text)
    if m:
        head = f"{m.group(1)}/{m.group(2)}сб"
    else:
        m = _LAST4_RE.search(text)
        if not m:
            return None
        head = m.group(1)

    # Извлекаем спец-номер из «спец…/N»
    spec = _SPEC_CONTRACT_RE.search(text)
    return _compose(head, spec.group(1) if spec else None)
