"""Единый формат ключа ГК в справочнике и в отчёте.

Правило формирования ключа:
    - Если в договоре/имени файла ЕСТЬ спец -> ключ «ИГК спец» (сб НЕ пишется)
    - Если спеца НЕТ, но есть сб           -> ключ «ИГК/NNNсб»
    - Если нет ни спеца, ни сб             -> ключ «ИГК»

Примеры:
    Excel: «…/481сб/137 от 24.09.2019, спец…/139»  -> «7717 139»
    Excel: «…/393сб/137 от 21.10.2025»             -> «…/393сб»
    Архив: «…_481сб_137_139.xls»                   -> «7717 139» (два числа после сб: договор + спец)
    Архив: «…_406сб_137.xls»                       -> «…/406сб» (одно число после сб = номер договора)
    Архив: «…_139.xls» (без сб)                    -> «7717 139» (спец без сб)
    Архив: «…1493.xls» (без хвоста)                -> «1493»
"""

import re

# --- Регулярные выражения ---

# Спец-номер в строке договора: «спец…/5», «спец. …/175», «Спец…205»
_SPEC_CONTRACT_RE = re.compile(r"спец\D*?(\d+)", re.IGNORECASE)

# Последние 4 цифры длинного номера = ИГК
_LAST4_RE = re.compile(r"(\d{4})(?!\d)")

# Номер сборочного контракта: «/481сб», «_481сб», «481сб»
_SB_RE = re.compile(r"[_/\s\-]*(\d+)\s*[сc]б", re.IGNORECASE)

# Два числа после сб: «_137_139» -> договор 137, спец 139
_TWO_TAIL_RE = re.compile(r"^[_/\s\-]+(\d+)[_\s\-]+(\d+)$")

# Одно число после сб через пробел: « 5» (старый формат ручной записи) -> спец
_SPACE_TAIL_RE = re.compile(r"^\s+(\d+)$")

# Хвост без сб: «_12» или « 12» в конце строки -> спец
_PLAIN_TAIL_RE = re.compile(r"^[_/\s\-]+(\d+)$")


# --- Разбор текста на части ---


def _key_parts(text):
    """Разбирает текст (договор или имя файла) на (игк, спец, сб).

    Возвращает кортеж (igk, spec, sb), где заполнено либо spec, либо sb,
    либо ничего (только игк).
    """
    m = _LAST4_RE.search(text)
    if not m:
        return None, None, None
    igk = m.group(1)
    rest = text[m.end() :]

    # 1. Есть слово «спец» -> спец найден, сб игнорируется
    spec_m = _SPEC_CONTRACT_RE.search(text)
    if spec_m:
        return igk, spec_m.group(1), None

    # 2. Ищем сб после ИГК
    sb_m = _SB_RE.search(rest)
    if sb_m:
        after = rest[sb_m.end() :]
        # «_137_139» — два числа: первое договор, второе спец (сб игнорируется)
        two = _TWO_TAIL_RE.match(after)
        if two:
            return igk, two.group(2), None
        # « 5» — число через пробел (старый ручной формат) — это спец
        space = _SPACE_TAIL_RE.match(after)
        if space:
            return igk, space.group(1), None
        # «_137» или «/137 от …» — одно число = номер договора, оставляем сб
        return igk, None, sb_m.group(1)

    # 3. Сб нет: хвост «_12» в конце строки = спец
    tail = _PLAIN_TAIL_RE.match(rest.strip())
    if tail:
        return igk, tail.group(1), None

    # 4. Ни спеца, ни сб — только ИГК
    return igk, None, None


def _compose(igk, spec, sb):
    """Собирает ключ из разобранных частей."""
    if spec:
        return f"{igk} {spec}"
    if sb:
        return f"{igk}/{sb}сб"
    return igk


# --- Публичные функции ---


def parse_gk_key(value):
    """Нормализует метку ГК (имя файла, старый ключ) к новому формату.

    Примеры:
        «7717_481сб_137_139» -> «7717 139»
        «7717_406сб_137»     -> «7717/406сб»
        «7717_139»           -> «7717 139»
        «7717/481сб 139»     -> «7717 139» (старый формат приводится к новому)
        «7717»               -> «7717»
    """
    igk, spec, sb = _key_parts(str(value or "").strip())
    if igk is None:
        return None
    return _compose(igk, spec, sb)


def gk_key(value):
    """Ключ ГК; если разобрать не удалось — строка без изменений."""
    text = str(value or "").strip()
    return parse_gk_key(text) or text


def key_from_contract(text):
    """Ключ из строки «Договор/Дата» справочника.

    Примеры:
        «…/481сб/137 от 24.09.2019, спец…/139» -> «7717 139» (спец есть — сб не пишем)
        «…/393сб/137 от 21.10.2025»            -> «…/393сб» (спеца нет — пишем сб)
        «…/137 от 16.03.2021г.»                -> «…» (только ИГК)
    """
    igk, spec, sb = _key_parts(str(text or ""))
    if igk is None:
        return None
    return _compose(igk, spec, sb)
